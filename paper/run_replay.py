"""Historical REPLAY of paper engine v3 (same code path as live paper) -> paper/reports/.

  python -m paper.run_replay        # needs research/data/angel (see research/README.md)

Window: 08-Aug-2021 → latest (this period was ALREADY inspected in v1/v2 – it is not untouched test data).
Two roll treatments, both labelled:
  estimated : research series back-adjusted by ESTIMATED roll gaps (replay only – never used live)
  strict    : vendor series as recorded; every detected switch is an UNKNOWN gap -> signals near it are refused
              and held positions are closed before it. This is how the live engine behaves until it has recorded
              both contracts around each roll.
Risk 0.25% / 0.5% / 1% of equity per trade, long-only. A replay of history, NOT forward paper trading.
"""
import copy, json
from pathlib import Path
import pandas as pd
from paper import mcx_daily as P

OUT = Path(__file__).resolve().parent / "reports"
START = "2021-08-08"


def kind(a):
    if a["status"] != "NO TRADE":
        return f"{a['status']} ({a.get('stage') or '-'})"
    b = " ".join(a.get("blocks") or [])
    k = ("RSI rule" if "RSI" in b else "chase / open below breakout" if ("chase" in b or "back below" in b) else
         "unknown roll gap" if "UNKNOWN" in b else "size: 1 lot too big" if "even 1 lot" in b or "per-trade" in b else
         "portfolio limit" if ("exceed" in b or "max " in b or "margin" in b) else "data" if "data" in b else "other")
    return f"NO TRADE ({a.get('stage')}) – {k}"


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("replay_*"):
        old.unlink()
    base = copy.deepcopy(P.CFG)
    rows, samples = [], {}
    for mode in ("estimated", "strict"):
        for rp in (0.0025, 0.005, 0.01):
            P.CFG.clear(); P.CFG.update(copy.deepcopy(base)); P.CFG.update(risk_pct=rp, max_open_risk_pct=4 * rp, group_risk_pct=2 * rp)
            label = f"replay_{mode}_risk{rp * 100:g}"
            book, eng = P.replay(START, mode=mode, state_dir=OUT / "state" / label)
            res = P.report(book, OUT, label)
            rows.append(dict(mode=mode, risk_per_trade_pct=rp * 100,
                             **{k: v for k, v in res.items() if not isinstance(v, dict)},
                             alerts_by_status=json.dumps(res.get("alerts_by_status", {}), ensure_ascii=False)))
            if mode == "estimated" and rp == 0.005:
                for a in eng.alerts:
                    samples.setdefault(kind(a), a["text"])
            print(label, {k: res.get(k) for k in ("closed_trades", "net_pnl_rs", "return_pct", "max_dd_pct", "avg_R", "win_pct")}, flush=True)
    P.CFG.clear(); P.CFG.update(base)
    pd.DataFrame(rows).to_csv(OUT / "replay_summary.csv", index=False)
    (OUT / "SAMPLE_ALERTS.md").write_text(
        "# Sample paper alerts (generated by the v3 engine during the 'estimated' replay at 0.5% risk)\n\n"
        "Contract shows the replay series name because history has no per-day contract; live alerts show the real "
        "contract symbol and expiry (see paper/tests).\n\n" +
        "\n\n".join(f"## {k}\n```\n{v}\n```" for k, v in sorted(samples.items())) + "\n")


if __name__ == "__main__":
    main()
