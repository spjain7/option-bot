import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from research.mcxe005.select_eval import load, LABEL, CELLS  # noqa: E402

D = ROOT / "research/mcxe005"
RES = D / "results"


def tbl(df, nd=3):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(("—" if (isinstance(x, float) and not np.isfinite(x)) else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))) for x in r) + " |")
    return "\n".join(out)


def per_cell_family():
    """family x side, filter none, exit X1, DEV / VALID pooled metrics (no OOS – OOS is only read for frozen survivors)."""
    out = []
    for cell in CELLS:
        T = load(cell)
        if T is None:
            continue
        x = T[(T.filt == "none") & (T.exit == "X1")]
        for (hz, tf, fam, side), g in x.groupby(["horizon", "tf", "fam", "side"], observed=True):
            rec = dict(market=LABEL[cell], horizon=hz, tf=tf, family=fam, side="BUY" if side > 0 else "SELL")
            for P in ("DEV", "VALID"):
                y = g[g.period == P]
                rec[f"{P} n"] = len(y)
                rec[f"{P} win%"] = round(100 * (y.r1 > 0).mean(), 1) if len(y) else np.nan
                rec[f"{P} exp 1x"] = round(y.r1.mean(), 3) if len(y) else np.nan
                rec[f"{P} exp 2x"] = round(y.r2.mean(), 3) if len(y) else np.nan
            out.append(rec)
    return pd.DataFrame(out)


def main():
    REG = pd.read_csv(D / "STRATEGY_EXPERIMENT_REGISTER.csv")
    A = pd.read_csv(RES / "ablation_filters.csv")
    O = pd.read_csv(RES / "oos_survivors.csv") if (RES / "oos_survivors.csv").exists() else pd.DataFrame()
    S4 = pd.read_csv(RES / "s4_study.csv")
    FC = per_cell_family()
    FC.to_csv(RES / "family_dev_valid.csv", index=False)

    # ---------- ACCURACY_COMPARISON ----------
    L = ["# MCXE-005 accuracy comparison (generated by summarise.py)", "",
         "- All numbers are net R per trade after realistic costs (1×) and at 2× stress.",
         "- Win % = net R > 0. DEV / VALID / OOS are never combined.",
         "- OOS was read once, and only for the 4 frozen survivors and the S4 study.",
         "- Windows: approved MCXE-004 one-year windows only.", "",
         "## 1. Selection outcome by market cell (every tested cell is in STRATEGY_EXPERIMENT_REGISTER.csv)", ""]
    g = REG.groupby(["cell", "outcome"]).size().unstack(fill_value=0)
    g.index = [LABEL.get(i, i) for i in g.index]
    L += [tbl(g.reset_index().rename(columns={"index": "market cell"})), ""]
    t = REG[(REG.n_DEV >= 40) & (REG.nd_DEV >= 25)]
    sh = t.groupby("cell").agg(testable=("m_DEV", "size"), dev_pos_2x=("m_DEV", lambda s: round(100 * (s > 0).mean(), 1)),
                                q_lt_010=("q_DEV", lambda s: int((s < 0.10).sum())),
                                both_pos=("m_DEV", lambda s: np.nan)).reset_index()
    sh["both_pos"] = [round(100 * ((t[t.cell == c].m_DEV > 0) & (t[t.cell == c].m_VALID > 0)).mean(), 1) for c in sh.cell]
    sh["cell"] = sh.cell.map(LABEL)
    L += ["Testable cells (DEV ≥ 40 trades on ≥ 25 dates): % with DEV expectancy > 0 at 2× cost, number significant after BH,",
          "and % positive in both DEV and VALID at 2×.", "",
          tbl(sh.rename(columns={"dev_pos_2x": "% DEV 2x > 0", "q_lt_010": "BH q < 0.10", "both_pos": "% DEV & VALID 2x > 0"})), ""]
    L += ["## 2. Frozen survivors – DEV, VALID and OOS (evaluated once)", ""]
    if len(O):
        rows = []
        for r in O.itertuples():
            dv, va, oo = json.loads(r.dev), json.loads(r.valid), json.loads(r.oos)
            for P, m in (("DEV", dv), ("VALID", va), ("OOS", oo)):
                rows.append(dict(strategy=f"{r.fam} {'BUY' if r.side > 0 else 'SELL'} +{r.filt} {r.exit}", period=P, trades=m["trades"], dates=m["dates"],
                                 **{"win %": m["win_pct"], "avg win": m["avg_win"], "avg loss": m["avg_loss"], "exp 1x": m["exp_1x"], "exp 2x": m["exp_2x"],
                                    "PF": m["pf"], "stop %": m["stop_pct"], "target %": m["target_pct"]}))
        L += [tbl(pd.DataFrame(rows)), "", "OOS status (register.classify; matched baseline = all 'none'-filter signals of the same cell, side, exit, instruments and OOS period):", ""]
        L += [tbl(O[["fam", "side", "filt", "exit", "status", "oos_trades", "oos_dates", "oos_win", "oos_exp1", "oos_exp2", "oos_pf", "oos_maxdd", "oos_ci", "control_exp1"]].astype({"oos_ci": str})), ""]
        L += ["OOS by instrument / regime: `results/oos_survivors.csv` (columns by_inst_oos, by_regime_oos).", ""]
    L += ["## 3. Filter ablation (DEV + VALID, each filter vs the same family / side / exit with no filter)", "",
          "- \"helps\" = the day-bootstrap 95 % CI of the difference in 2× expectancy is above 0, and at least 30 % of the base",
          "  trades are kept.", "- By chance alone, about 2.5 % of comparisons would \"help\".", ""]
    a = A.groupby(["cell", "filt"]).agg(comparisons=("helps", "size"), helps=("helps", "sum"), median_d_exp2=("d_exp2", "median"),
                                        median_retention=("retention", "median"), median_base_win=("base_win", "median"),
                                        median_filt_win=("filt_win", "median")).reset_index()
    a["helps %"] = (100 * a.helps / a.comparisons).round(1); a["cell"] = a.cell.map(LABEL)
    L += [tbl(a), "",
          "Reading: \"helps\" is the share of family / side / exit combinations whose 2× expectancy improved with a CI above 0.",
          "The median retention shows how many trades the filter removes. A higher win % alone is not counted as an improvement.", ""]
    L += ["## 4. Existing live strategy S4 (stock-futures OI breakout): baseline vs research variants", "",
          "- `S4_exact_EMA200` is the production rule. Inside the one-year window it can only signal from about Sep-2026, so",
          "  almost all of its trades fall in OOS.",
          "- `S4_proxy_EMA50` is a research proxy with DEV coverage. Every variant changes exactly one thing against it.", ""]
    L += [tbl(S4[["base", "variant", "signals", "cancelled", "DEV_trades", "DEV_win", "DEV_exp1", "DEV_exp2", "VALID_trades", "VALID_win", "VALID_exp1",
                  "VALID_exp2", "OOS_trades", "OOS_win", "OOS_exp1", "OOS_exp2", "OOS_pf", "OOS_maxdd", "OOS_ci"]].astype({"OOS_ci": str})), ""]
    L += ["## 5. Family results per market cell (filter none, exit X1; DEV and VALID only)", "",
          "Full table: `results/family_dev_valid.csv`. Below, the 15 best and 15 worst rows by DEV 2× expectancy, among rows",
          "with DEV n ≥ 40.", ""]
    fc = FC[FC["DEV n"] >= 40].sort_values("DEV exp 2x", ascending=False)
    L += [tbl(fc.head(15)), "", tbl(fc.tail(15)), ""]
    (D / "ACCURACY_COMPARISON.md").write_text("\n".join(L))

    # ---------- FAILED ----------
    F = ["# MCXE-005 failed strategies (every cell is kept in STRATEGY_EXPERIMENT_REGISTER.csv)", ""]
    rr = REG.copy(); rr["reason_type"] = rr.reason.str.split(" ").str[:3].str.join(" ")
    F += ["## Failure reasons by market cell", "", tbl(REG.groupby(["cell", "outcome"]).size().rename("cells").reset_index().assign(cell=lambda x: x.cell.map(LABEL))), ""]
    F += ["## Why they failed (measured)", ""]
    for cell in CELLS:
        t = REG[(REG.cell == cell) & (REG.n_DEV >= 40) & (REG.nd_DEV >= 25)]
        if not len(t):
            continue
        both = ((t.m_DEV > 0) & (t.m_VALID > 0)).mean()
        flip = ((t.m_DEV > 0) & (t.m_VALID <= 0)).sum() / max((t.m_DEV > 0).sum(), 1)
        gross_gap = (t.m_DEV - t.n_DEV * 0).median()
        F.append(f"- **{LABEL[cell]}**:")
        F.append(f"  - {len(t)} testable cells; {100 * (t.m_DEV > 0).mean():.0f} % positive in DEV at 2× cost;")
        F.append(f"  - {int((t.q_DEV < 0.10).sum())} significant after BH;")
        F.append(f"  - of the DEV-positive cells, {100 * flip:.0f} % turned ≤ 0 in VALID (regime flip / noise);")
        F.append(f"  - positive in both: {100 * both:.0f} %; median DEV 2× expectancy {t.m_DEV.median():+.3f}R.")
    F += ["",
          "**Patterns seen:**",
          "- **No information after costs on intraday horizons.**",
          "  - MCX, NSE cash and NSE futures intraday: the median cell is below zero at 2× cost.",
          "  - The few positive DEV cells do not survive BH, or flip in VALID. This matches MCXE-003, where intraday pattern",
          "    information was absent or below costs.",
          "- **Regime dependence on daily horizons.**",
          "  - Strong DEV results (Nov-2025 – May-2026) often turn negative in VALID (May – Aug 2026).",
          "  - Example: the S4 proxy, +0.72R DEV → −0.14R VALID → −0.11R OOS.",
          "- **SELL-side survivors and market drift.**",
          "  - The surviving cells are stock-futures SELL rules (trend down + ADX ≥ 20).",
          "  - In OOS the plain all-signal SELL baseline earned +0.22 to +0.32R, so much of their OOS profit is a falling-market",
          "    effect, not the pattern.",
          "- **Filters raise win % more often than expectancy.** See the ablation table in ACCURACY_COMPARISON.md: most filters",
          "  cut trades heavily without a CI-backed gain.",
          "",
          "## The 4 OOS-evaluated cells – rejection reasons", ""]
    if len(O):
        F += [tbl(O[["fam", "side", "filt", "exit", "status", "reason", "oos_trades", "oos_exp1", "oos_ci", "control_exp1"]].astype({"oos_ci": str})), ""]
    (D / "FAILED_STRATEGIES.md").write_text("\n".join(F))

    # ---------- WINNING ----------
    win = O[O.status.isin(["VALIDATED_CANDIDATE", "PAPER_ONLY"])] if len(O) else O
    Wd = ["# MCXE-005 winning strategies", ""]
    if not len(win):
        Wd += ["**None.** No strategy met the pre-registered OOS acceptance bar inside the approved one-year windows.", "",
               "Closest results (OOS read once; all REJECTED because the conservative 95 % CI includes 0):", ""]
        if len(O):
            for r in O.sort_values("oos_exp2", ascending=False).itertuples():
                Wd += [f"### {r.fam} SELL + {r.filt} · exit {r.exit} · NSE stock futures · daily · positional",
                       "",
                       f"- **Logic:** daily close on point-in-time front-month futures; the {'EMA50 slope (EMA50 − EMA50 five bars ago) crosses below 0' if r.fam == 'A_EMA50_SLOPE' else 'MACD(12,26) crosses below 0'} "
                       f"and ADX(14) ≥ 20 → SELL.",
                       f"- **Entry and exit:** entry at the next open. "
                       + ("Stop 2 ATR; target 3R; max 20 sessions." if r.exit == "X1" else "Stop 1.5 ATR; 2.5-ATR trailing stop; max 20 sessions.")
                       + " No holding across a roll.",
                       f"- **OOS:** {r.oos_trades} trades on {r.oos_dates} dates · win {r.oos_win}% · expectancy {r.oos_exp1:+.3f}R (2×: {r.oos_exp2:+.3f}R) ·",
                       f"  PF {r.oos_pf} · max DD {r.oos_maxdd}R · CI {r.oos_ci}.",
                       f"- **Matched all-signal SELL baseline:** {r.control_exp1:+.3f}R.",
                       f"- **Status: {r.status}.** {r.reason}",
                       "- **Limitations:** 3-month OOS; a falling-market period for stocks; 51 trades on fewer than 30 dates.",
                       "- **Eligible for paper testing?** Not under the pre-registered rule. At most a watch-list item for forward",
                       "  logging.", ""]
    else:
        for r in win.itertuples():
            Wd += [f"### {r.fam} {'BUY' if r.side > 0 else 'SELL'} + {r.filt} · {r.exit} ({r.cell})", f"status {r.status}: {r.reason}", ""]
    Wd += ["**Not advertised:** no accuracy figure in this research supports claims like \"80–90 % accurate\". The highest OOS",
           "win % among the evaluated cells (≈ 71 %) comes with a CI that includes 0 expectancy, on 51 trades."]
    (D / "WINNING_STRATEGIES.md").write_text("\n".join(Wd))
    print("written: ACCURACY_COMPARISON.md, FAILED_STRATEGIES.md, WINNING_STRATEGIES.md")


if __name__ == "__main__":
    main()
