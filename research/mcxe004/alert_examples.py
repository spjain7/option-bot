"""Transparent alert cards (register.alert_card) for REAL signals the live bot sent on 5/6-Nov-2026 (alerts-state ledger),
joined to the window evaluation of the rule that produced them. Research view only – nothing is sent.
python research/mcxe004/alert_examples.py -> ALERT_CARD_EXAMPLES.md"""
import json
import sys
from pathlib import Path
import pandas as pd
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from research.mcxe004 import register as RG  # noqa: E402

D = ROOT / "research/mcxe004"
MAP = {("ICICIBANK", "Daily RSICONT"): "RB_STK_1d_RSI80_BUY", ("GOLD", "3-Hour Ema 13/48 Cross"): None,
       ("NIFTY", "Daily EMAX"): None, ("BANKNIFTY", "Daily RSICONT"): None}
WHY = {None: "no research-parity window evaluation exists for this rule (index futures are outside MCXE-004 scope; "
             "the MCX 3h EMA13/48 engine rule has no window evaluation) -> treated as RESEARCH_ONLY / unevaluated"}


def main():
    recs = {r["strategy_name"]: r for r in json.loads((D / "results/e1_records.json").read_text())}
    L = pd.read_csv(D / "evidence/live_ledger_6nov.csv")
    L = L[L.date >= "2026-11-05"]
    out = ["# Transparent alert cards – real live signals of 5/6-Nov-2026 with their 1-year-window evidence", "",
           "- These cards are generated by `register.alert_card` (research view; nothing is sent).",
           "- Accuracy appears only as an OOS historical frequency, with trades, dates and CI. It is never a prediction.", ""]
    for r in L.itertuples():
        rid = MAP.get((r.name, r.type), "n/a")
        ev = recs.get(rid) if rid else None
        sig = dict(strategy=r.type, script_id=rid or "live engine (no research parity)", market=r.seg, instrument=r.name, side=r.side,
                   entry=r.entry, sl=r.sl, target=None if pd.isna(r.target) else r.target, invalidation=f"stop {r.sl}",
                   time=r.date, timeframe=r.type, data_age_min="n/a (from ledger)", cost_R="see rule evaluation")
        card = RG.alert_card(sig, ev or dict(validation_status="RESEARCH_ONLY", conclusion=WHY[None] if rid is None else "rule not in E1"))
        out += [f"## {r.name} {r.side} – {r.type} ({r.date})", "", "```", card, "```", ""]
    for name in ("RB_STK_3h_MACD0_SELL", "RB_STK_3h_EMA921_SELL", "SHADOW_MCX_DTC_GOLD_SILVER"):
        ev = recs[name]
        sig = dict(strategy=name, script_id="MCXE004-E1", market=ev["market"], instrument="(example)", side="SELL" if "SELL" in name else "BUY/SELL",
                   time="(next signal)", timeframe=ev["timeframe"], data_age_min="n/a", cost_R=(ev.get("costs") or {}).get("median_cost_R"))
        out += [f"## Template for {name}", "", "```", RG.alert_card(sig, ev), "```", ""]
    (D / "ALERT_CARD_EXAMPLES.md").write_text("\n".join(out))
    print("\n".join(out)[:3000])


if __name__ == "__main__":
    main()
