"""MCXE-004 report generator – every table is computed from the actual result files (register, e1_trades, e1_signals,
script_inventory.csv, evidence/*). Nothing is typed in by hand except the explanatory text.
Writes: SCRIPT_INVENTORY.md · EXECUTION_REGISTER.md (+ register/executions.csv, register/historical_backfill.jsonl) ·
RESULTS_BY_SCRIPT.md · ACCURACY_SUMMARY.md · SCRIPT_STATUS_LISTS.md
python research/mcxe004/report.py"""
import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from research.mcxe004 import register as RG, window as W  # noqa: E402

D = ROOT / "research/mcxe004"
RES = D / "results"


def fmt(v, nd=3):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "—"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(fmt(x) if not isinstance(x, str) else x.replace("|", "/") for x in r) + " |")
    return "\n".join(out)


def latest(R):
    R = R.copy()
    R["k"] = R.script_id.astype(str) + "|" + R.strategy_name.astype(str)
    return R.sort_values("execution_end").groupby("k").tail(1)


def inventory_md():
    T = pd.read_csv(D / "script_inventory.csv")
    lines = ["# MCXE-004 script inventory (generated by inventory.py; evidence-based)", "",
             "**Execution evidence rules:** a script counts as executed only if an output file it writes is committed (date of",
             "that commit), or if the live market-loop log of 6-Nov-2026 shows it running, or if a workflow schedules it. A file",
             "existing is not evidence. \"DEFINED ONLY\" means none of these: it may have run locally, but that is not claimed.",
             "", "## Counts", "", md_table(T.groupby(["repo", "execution"]).size().rename("scripts").reset_index()), ""]
    for repo in ("main", "research"):
        x = T[T.repo == repo].sort_values(["execution", "file"])
        lines += [f"## {'Live code on main' if repo == 'main' else 'Research code (exp/strategy-program-001)'} – {len(x)} files", ""]
        cols = ["script_id", "execution", "markets", "timeframes", "produces", "outputs_committed", "last_output_commit",
                "last_code_commit", "scheduled", "summary"]
        if repo == "main":
            cols.insert(2, "live_log_evidence_6nov")
        y = x[cols].copy()
        y["summary"] = y.summary.fillna("").str.slice(0, 120)
        lines += [md_table(y.fillna("—")), ""]
    (D / "SCRIPT_INVENTORY.md").write_text("\n".join(lines))
    return T


def backfill(T):
    """historical (pre-MCXE-004) executions -> register records with nulls where nothing was recorded."""
    p = D / "register/historical_backfill.jsonl"
    rows = []
    for r in T[T.execution.str.startswith("EXECUTED") & (T.repo == "research")].itertuples():
        rec = {k: None for k in RG.FIELDS}
        rec.update(experiment_id=f"HIST-{r.script_id}", script_id=r.script_id, strategy_name=r.file, status="COMPLETED",
                   progress_stage="historical (before the execution register existed)", execution_end=r.last_output_commit,
                   validation_status="RESEARCH_ONLY", artifact_paths=[r.example_output],
                   conclusion="pre-MCXE-004 research run; its data window predates or exceeds the 1-year rule, so its "
                              "results are idea sources only, not current evidence (see research/program/REPORT.md)",
                   error_details=None, code_commit=None)
        rows.append(rec)
    p.write_text("\n".join(json.dumps(x) for x in rows) + "\n")
    return len(rows)


def register_md(R):
    L = latest(R)
    cols = ["experiment_id", "script_id", "strategy_name", "market", "timeframe", "data_start_date", "data_end_date", "status",
            "validation_status", "total_signals", "executed_backtest_trades", "rejected_signals", "win_rate", "net_expectancy_R",
            "profit_factor", "code_commit"]
    R.to_csv(D / "register/executions.csv", index=False)
    lines = ["# MCXE-004 research execution register", "",
             "- Source: `register/executions.jsonl`, append-only, one JSON line per execution, with every required field.",
             "- CSV copy: `register/executions.csv`.",
             "- **win_rate / expectancy / profit factor are OOS values** (the last 3 months of the window). Per-period values are in",
             "  `results/e1_records.json` and in RESULTS_BY_SCRIPT.md.",
             "- Missing values are blank (null), never estimated.",
             f"- Records: {len(R)}, of which the latest per strategy: {len(L)}.",
             "- Earlier failed development runs (an index bug in `metrics`, caught by the register as FAILED/ERROR) are kept in",
             "  `register/executions_devrun_7nov.jsonl`.",
             "- Historical (pre-register) research executions: `register/historical_backfill.jsonl`. They are COMPLETED with",
             "  RESEARCH_ONLY status and null metrics, because they were never recorded at the time.", "",
             md_table(L[cols].fillna("—")), "", "## Conclusions / reasons (latest record per strategy)", ""]
    for r in L.itertuples():
        lines.append(f"- **{r.strategy_name}** ({r.script_id}) – {r.status} / {r.validation_status}: {r.conclusion}")
        if isinstance(r.rejection_reasons, dict) and r.rejection_reasons:
            lines.append("  - rejected signals: " + "; ".join(f"{k}: {v}" for k, v in r.rejection_reasons.items() if v))
    (D / "EXECUTION_REGISTER.md").write_text("\n".join(lines))
    return L


def results_md():
    T = pd.read_csv(RES / "e1_trades.csv.gz", parse_dates=["date", "t_out"])
    recs = json.loads((RES / "e1_records.json").read_text())
    wk = {"MCX": "MCX", "STOCKS": "NSE_FUT_INTRADAY"}
    T["period"] = [W.period(pd.Series([d]), wk[m])[0] for d, m in zip(T.date, T.mkt)]
    T["hold_days"] = (T.t_out - T.date).dt.total_seconds() / 86400
    T["holding"] = np.where(T.t_out.isna(), "intraday (same session)", np.where(T.hold_days < 1, "< 1 day", np.where(T.hold_days <= 5, "1-5 days", "> 5 days")))
    T["side_txt"] = np.where(T.side > 0, "BUY", "SELL")
    lines = ["# MCXE-004 script-wise results – E1: live / shadow rules inside the 1-year window", "",
             "- Script `eval_live_rules.py` (`MCXE004-E1`), run at code commit " + (recs[0].get("code_commit") or "—") + ".",
             "- Trades: `results/e1_trades.csv.gz`. Signals and rejection reasons: `results/e1_signals.csv`.",
             "- **Units:** net R per trade after realistic costs (1×). The 2× stress value is shown separately. Rupee P&L is",
             "  not modelled, because lot sizing is not part of the rules.",
             "- **Periods:** DEV, VALID and OOS of the approved window. MCX is 2025-11-04 → 2026-11-03, but its frames end on",
             "  2026-10-21 (Angel 1-hour). Stocks are 2025-10-23 → 2026-10-22.",
             "- **Contamination:** every one of these rules was **selected on 2022-26 data that includes this window**. So the",
             "  window is not independent evidence for them; their best possible status is PAPER_ONLY.", ""]
    for r in recs:
        rid = r["strategy_name"]; x = T[T.rule == rid]
        lines += [f"## {rid} — {r['validation_status']}", "", f"{r['conclusion']}", ""]
        lines.append(f"signals {r['total_signals']} · executed trades {r['executed_backtest_trades']} · rejected {r['rejected_signals']} "
                     f"· reasons: {json.dumps(r.get('rejection_reasons') or {})}")
        lines.append("")
        rows = []
        for P in ("DEV", "VALID", "OOS"):
            for cm in ("r1", "r2"):
                m = r["periods"][P][cm]
                rows.append([P, "1×" if cm == "r1" else "2×", m["trades"], m["wins"], m["losses"], m["win_rate"], m["avg_win"],
                             m["avg_loss"], m["expectancy_R"], m["profit_factor"], m["net_R"], m["max_drawdown_R"], m["unique_dates"],
                             str(m["ci95"]) if m["ci95"] else "—"])
        lines += [md_table(pd.DataFrame(rows, columns=["period", "cost", "trades", "wins", "losses", "win %", "avg win R", "avg loss R",
                                                       "expectancy R", "PF", "net R", "max DD R", "dates", "95% CI (cons.)"])), ""]
        if len(x):
            g = x.groupby(["inst", "period"]).r1.agg(["size", "mean"]).unstack("period")
            g.columns = [f"{a}_{b}" for a, b in g.columns]
            g = g.reset_index()
            lines += ["By instrument (net R 1×; n / mean):", "", md_table(g.round(3).fillna("—")), ""]
    lines += ["## Breakdowns across all E1 trades (1× cost)", ""]
    for by in (["mkt", "period"], ["side_txt", "period"], ["holding", "period"], ["tf", "period"]):
        g = T.groupby(by).r1.agg(trades="size", win_pct=lambda s: round(100 * (s > 0).mean(), 1), expectancy_R="mean", net_R="sum").reset_index()
        lines += [f"### by {' × '.join(by)}", "", md_table(g.round(3)), ""]
    (D / "RESULTS_BY_SCRIPT.md").write_text("\n".join(lines))
    return T, recs


def accuracy_md(recs, R):
    ev = pd.read_csv(D / "evidence/live_ledger_6nov.csv")
    c = ev[ev.status == "CLOSED"].copy()
    c["kind"] = np.where(c.note.astype(str).str.contains("withdrawn|cancelled", case=False), "withdrawn / cancelled", "outcome")
    out = c[c.kind == "outcome"]
    lines = ["# MCXE-004 accuracy and profitability summary", "",
             "- **Accuracy** = the share of trades with net R > 0 after realistic costs. It is always shown with the number of",
             "  trades, the number of unique dates and the 95 % CI of expectancy (day-block bootstrap + cluster t, widest).",
             "- In-sample (DEV), validation (VALID), out-of-sample (OOS) and forward live results are **never combined**.",
             "- Scripts that only produce signals or statistics (no trade outcomes) are listed as SIGNAL-ONLY, with no accuracy.", "",
             "## OOS (last 3 months of the window) – live / shadow rules with research code", "",
             "| strategy | market | status | OOS trades | dates | wins | win % | expectancy R (1×) | expectancy R (2×) | PF | max DD R | 95% CI | DEV exp R (n) | VALID exp R (n) |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in recs:
        o = r["periods"]["OOS"]["r1"]; o2 = r["periods"]["OOS"]["r2"]
        dv, va = r["periods"]["DEV"]["r1"], r["periods"]["VALID"]["r1"]
        lines.append(f"| {r['strategy_name']} | {r['market']} | {r['validation_status']} | {o['trades']} | {o['unique_dates']} | "
                     f"{o['wins']} | {fmt(o['win_rate'], 1)} | {fmt(o['expectancy_R'])} | {fmt(o2['expectancy_R'])} | {fmt(o['profit_factor'], 2)} | "
                     f"{fmt(o['max_drawdown_R'], 1)} | {o['ci95'] or '—'} | {fmt(dv['expectancy_R'])} ({dv['trades']}) | {fmt(va['expectancy_R'])} ({va['trades']}) |")
    blocked = latest(R)
    blocked = blocked[blocked.validation_status == "BLOCKED"]
    lines += ["", "## Not evaluable inside the window (BLOCKED – exact reasons)", ""]
    for r in blocked.itertuples():
        lines.append(f"- **{r.strategy_name}** ({r.market}): {r.conclusion}")
    lines += ["", "## Forward live record (alerts actually sent; `alerts-state` ledger, 28-Oct → 6-Nov-2026)", "",
              f"- Calls in the ledger: {len(ev)}; closed: {len(c)}.",
              f"  - withdrawn or cancelled before an outcome: {int((c.kind != 'outcome').sum())};",
              f"  - **with a real outcome: {len(out)}** (wins {int((out.gross_R > 0).sum())}, losses {int((out.gross_R < 0).sum())},",
              f"    gross R sum {out.gross_R.sum():+.2f}, before costs).",
              "- **INSUFFICIENT DATA:** 6 outcomes cannot support any accuracy statement.",
              "- The live calls show *backtest* statistics from 2006-26 / 2022-26 (rulebook tier text). Under the 1-year rule those",
              "  are **not current evidence**.", "",
              "## SIGNAL-ONLY / statistics-only scripts (no trade-level accuracy is computed)", "",
              "- MCXE-003 stage 1 (`run_discovery.py`, `daily.py`, `stage1.py`): event studies; information in ATR vs controls, not",
              "  trades. Results are pre-window, so they are idea sources only.",
              "- `research/program/` studies whose committed outputs are summaries only (see SCRIPT_INVENTORY.md, column \"produces\").",
              "",
              "## Bottom line (computed from the records above)", ""]
    st = pd.Series([r["validation_status"] for r in recs]).value_counts().to_dict()
    pap = [r for r in recs if r["validation_status"] == "PAPER_ONLY"]
    enough = [r for r in recs if r["validation_status"] in ("PAPER_ONLY", "REJECTED", "VALIDATED_CANDIDATE")]
    pos = [r for r in enough if (r["oos"]["expectancy_R"] or 0) > 0]
    lines += [f"- Status counts across {len(recs)} evaluated rules: " + ", ".join(f"{k} {v}" for k, v in st.items()) +
              f"; plus {len(blocked)} BLOCKED cells.",
              f"- {len(enough)} rules have enough OOS trades. {len(pos)} of them have a positive OOS point estimate, but only "
              f"{len(pap)} also have a 95 % CI above zero.",
              f"- **VALIDATED_CANDIDATE: {st.get('VALIDATED_CANDIDATE', 0)}.**"]
    for r in pap:
        o = r["oos"]
        lines += [f"- **PAPER_ONLY: {r['strategy_name']}** – OOS {o['trades']} trades on {o['unique_dates']} dates, "
                  f"{o['win_rate']:.0f} % profitable, expectancy {o['expectancy_R']:+.2f}R (2×: "
                  f"{r['periods']['OOS']['r2']['expectancy_R']:+.2f}R), CI {o['ci95']}.",
                  "  - Not independent evidence: the rule was selected on 2022-26 data that includes this window.",
                  "  - The stock universe is today's F&O list (survivorship).",
                  "  - So it is a forward paper-tracking candidate, not proof of an edge. It is already live."]
    lines += ["- Daily rules: no OOS trades, because warm-up inside a 1-year window consumes the daily bars (INSUFFICIENT_DATA)."]
    (D / "ACCURACY_SUMMARY.md").write_text("\n".join(lines))


def status_lists(T, R):
    L = latest(R)
    nd = T[T.execution.str.startswith("DEFINED")]
    lines = ["# Scripts not executed, failing or blocked", "",
             f"## Not executed (no committed output, schedule or log evidence) – {len(nd)}", "",
             "Some may have been run locally; this is not claimed.", "",
             md_table(nd[["script_id", "file", "last_code_commit", "summary"]].assign(summary=nd.summary.fillna("").str.slice(0, 100)).fillna("—")), "",
             "## Failing (register FAILED / ERROR)", ""]
    dev = D / "register/executions_devrun_7nov.jsonl"
    sup = D / "register/executions_superseded_period_bug.jsonl"
    if sup.exists():
        lines.append(f"- {len(RG.load(sup))} records superseded on 7-Nov: `window.period()` mislabelled DEV / VALID / OOS when the "
                     "trade table had a non-0..n-1 index (caught by test_window_no_leakage; fixed; all strategies re-run). "
                     "Kept in `register/executions_superseded_period_bug.jsonl`; **those OOS numbers must not be used**.")
    if dev.exists():
        F = RG.load(dev); F = F[F.status == "FAILED"]
        lines.append(f"- {len(F)} development-run failures on 7-Nov (all `KeyError` in `register.metrics` index alignment; fixed;"
                     f" every affected strategy re-ran COMPLETED). Records kept in `register/executions_devrun_7nov.jsonl`.")
    cur = L[L.status == "FAILED"]
    lines.append(f"- Current failing executions: {len(cur)}" + ("" if not len(cur) else ": " + ", ".join(cur.strategy_name)))
    lines += ["- Live loop, 6-Nov run 42154958592 (alerts scans):",
              "  - **1 FAILED** scan (exit 2; Angel login / instrument-list DataException at 14:20 IST; no alerts in that slot);",
              "  - **1 BUDGET_EXHAUSTED** (14:02–14:19 IST: 35 of 67 API calls refused, 186 skipped);",
              "  - **22 RATE_LIMITED** of 60 scans.",
              "", "## Blocked / insufficient data (register)", ""]
    for r in L[L.validation_status.isin(["BLOCKED", "INSUFFICIENT_DATA"])].itertuples():
        lines.append(f"- {r.validation_status}: **{r.strategy_name}** – {r.conclusion}")
    (D / "SCRIPT_STATUS_LISTS.md").write_text("\n".join(lines))


def main():
    T = inventory_md()
    nb = backfill(T)
    R = RG.load()
    register_md(R)
    E, recs = results_md()
    accuracy_md(recs, R)
    status_lists(T, R)
    print("inventory", len(T), "· historical backfill", nb, "· register", len(R), "· E1 trades", len(E))


if __name__ == "__main__":
    main()
